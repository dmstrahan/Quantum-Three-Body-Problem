'''Separation probabilities of particles, initial and final'''

def separation_distribution(psi, dq, n_bins=120):
    '''This function takes our wavefunction and grid, and returns
    bins for our separation histogram accordingly (n_bins= fineness)'''
    prob=np.abs(psi)**2 * dq**4    #probability at each point, as a fraction of total prob
                                  #like a "probability element"
    p_flat=prob.ravel() #converting 4D array to 1D

    r_max  = max(r23.max(), r12.max(), r13.max()) * 1.02 #finds largest separation, then givese max and mins. *1.02 acts as
                                                          #a sort of "softening" parameter, ensuring no points excluded due to riunding errors
    bins   = np.linspace(0.0, r_max, n_bins + 1) #defines bins in space
    dr     = bins[1] - bins[0] #bin width
    centres = 0.5 * (bins[:-1] + bins[1:])
    #add each separation (on Jacobi grid)'s probability element to its corresponding bin
    p12, _=np.histogram(r12.ravel(), bins=bins,weights=p_flat)
    p23, _=np.histogram(r23.ravel(),bins=bins,weights=p_flat)
    p13, _=np.histogram(r13.ravel(),bins=bins,weights=p_flat)

    #converts from probability in a given bin to probaboltiy density at the bin's r value
    return p12/dr, p23/dr, p13/dr, centres, dr



