print(f'Max potential phase per step: {np.abs(V).max()*dt/(2*hbar):.4f} rad  (half-step)')


def split_step(psi):
    psi =exp_V_half * psi
    psi =np.fft.fftn(psi)
    psi =exp_T_full * psi
    psi =np.fft.ifftn(psi)
    psi =exp_V_half * psi
    return psi

