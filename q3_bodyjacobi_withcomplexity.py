'''Expectation value of complexity: <C_s> = sum |psi|^2 * C_s(q) * dq^4'''
# C_s(q)= l_rms(q)/l_mhl(q) is evaluated at each grid point q, then averaged over the probability density
#
# l_rms(q)= (1/M)*sqrt(sum_{a<b} m_a m_b r_ab(q)^2)
# 1/l_mhl(q)= (1/M^2)*sum_{a<b} m_a m_b / r_ab(q)
# C_s(q)= l_rms(q) / l_mhl(q)
#
# <C_s> = sum_q |psi(q)|^2 * C_s(q) * dq^4


m_total=3*m

#l_rms(q) and l_mhl(q)
sum_m2_r2_pointwise = m**2*(r12**2 + r23**2 + r13**2)
l_rms_pointwise =np.sqrt(sum_m2_r2_pointwise)/ m_total

#to prevent r_ab=0  before dividing
eps=1e-12
r12_safe =np.where(r12 > eps, r12, np.nan)
r23_safe =np.where(r23 > eps, r23, np.nan)
r13_safe =np.where(r13 > eps, r13, np.nan)

sum_m2_invr_pointwise =m**2*(1.0/r12_safe + 1.0/r23_safe + 1.0/r13_safe)
inv_l_mhl_pointwise =sum_m2_invr_pointwise/ m_total**2
l_mhl_pointwise =1.0/ inv_l_mhl_pointwise

C_s_pointwise = l_rms_pointwise / l_mhl_pointwise

with h5py.File(output_filepath, 'r') as f:
    dt_s = f.attrs['dt']
    dq_s = f.attrs['dq']
    keys = sorted(f.keys())

    times          = np.zeros(len(keys))
    C_s_exp_vals   = np.zeros(len(keys))

    for i, key in enumerate(keys):
        psi_t = f[key][:]
        step  = int(key.split('_')[1])
        times[i] = step * dt_s

        prob=np.abs(psi_t)**2 * dq_s**4   # probability element at each Jacobi grid point
        # mask out any grid points where C_s(q) is undefined
        valid = ~np.isnan(C_s_pointwise)
        prob_masked = np.where(valid, prob, 0.0)

        #renormalize so excluded near-singular probability mass doesn't mess with total (NOTE- what does this mean for conservation of probability?)
        excluded_mass = np.sum(prob) - np.sum(prob_masked)
        if excluded_mass > 1e-6 * np.sum(prob):
            print(f"  [warning] t={times[i]:.3f}: excluded {excluded_mass:.2e} "
                  f"probability mass near collision lines ({100*excluded_mass/np.sum(prob):.4f}%)")
        C_s_exp_vals[i] = np.sum(prob_masked * C_s_pointwise) / np.sum(prob_masked)

print("Expectation value <C_s> over time:")
