'''Cartesian position densities for all three particles'''
#   r1=  sqrt(2/3) * lambda
#   r2= -lambda/sqrt(6) + eta/sqrt(2)
#   r3= -lambda/sqrt(6) - eta/sqrt(2)
'''for each point (ex, ey, lx, ly) in Jacobi space, we find
the corresponding (xi, yi), then accumulate |psi|^2*dq^4 onto a
real spatisl histogram grid.'''

def jacobi_to_cartesian_densities(psi, q, dq, n_cart=80):
    '''
    Convert a 4D Jacobi wavefunction to 2D Cartesian marginal densities
    for each of the three particles.
    Returns (rho1, rho2, rho3), a 2D array of shape (n_cart, n_cart) cart_ax
    ; 1D array of Cartesian axis coordinates
    '''
    #conversion weights
    a =np.sqrt(2.0 / 3.0)
    b =-1.0 / np.sqrt(6.0)
    c =1.0/ np.sqrt(2.0)
    #reconstructs spatial grid, from jacobi results
    L_jac = q.max()
    r_max = max(abs(a)*L_jac,
                abs(b)*L_jac + abs(c)*L_jac) * 1.05 #1.05 avoids loss at edges
    cart_ax  = np.linspace(-r_max, r_max, n_cart)
    dr       = cart_ax[1] - cart_ax[0] #grid widths
    #recreates 2D arrays for each particle, of appropriate length
    rho1 = np.zeros((n_cart, n_cart))
    rho2 = np.zeros((n_cart, n_cart))
    rho3 = np.zeros((n_cart, n_cart))

    prob = np.abs(psi)**2 * dq**4   #converts wavefunction to probability at each point (Jacobi)
    #convert from 4D to 1D arrays for making histograms
    N = len(q)
    ex_flat=EX.ravel()
    ey_flat=EY.ravel()
    lx_flat=LX.ravel()
    ly_flat=LY.ravel()
    p_flat =prob.ravel()

    # Cartesian coordinates for each particle at every Jacobi grid point
    x1 = a*lx_flat; y1=a*ly_flat
    x2 = b*lx_flat + c*ex_flat; y2=b*ly_flat + c*ey_flat
    x3 = b*lx_flat - c*ex_flat; y3= b*ly_flat - c*ey_flat

    #creates centers and edges for bins, for x and y axes
    edges = [cart_ax[0] - dr/2,  cart_ax[-1] + dr/2]
    bins  = [np.linspace(edges[0], edges[1], n_cart+1)]*2 #x and y
    #for each jacobi grid, look at where particle is in real space,
    #access corresponding bin output, add probability to bin
    rho1, _, _ =np.histogram2d(x1,y1,bins=bins,weights=p_flat)
    rho2, _, _ =np.histogram2d(x2,y2,bins=bins,weights=p_flat)
    rho3, _, _ =np.histogram2d(x3,y3,bins=bins,weights=p_flat)

    return rho1, rho2, rho3, cart_ax


